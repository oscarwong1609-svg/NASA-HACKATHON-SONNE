"""Rasterises OFL pixel fonts at their native pixel size (no anti-aliasing) into Java source (game/FontData.java).

The font files are not in the repo. To regenerate, put them in tools/fonts/ and run:
    python3 tools/fontgen.py core/src/main/java/com/missionlab/game/FontData.java
Where to get them (all SIL Open Font License 1.1, licences in licenses/):
    npm pack @fontsource/tiny5 @fontsource/press-start-2p @fontsource/silkscreen   (files/*-latin-400-normal.woff)
    Departure Mono: https://departuremono.com (DepartureMono-Regular.otf)
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")
FONTS = [  # java name, file, native px size, line height
    ("SMALL", "tiny5-latin-400-normal.woff", 8, 10),
    ("BODY", "DepartureMono-Regular.otf", 11, 13),
    ("TITLE", "press-start-2p-latin-400-normal.woff", 8, 10),
    ("LABEL", "silkscreen-latin-400-normal.woff", 8, 9),
]
CHARS = [c for c in range(32, 127)] + [c for c in range(160, 256) if c != 173] + [0x2014, 0x2022, 0x00B7]
out = []
out.append("package com.missionlab.game;\n")
out.append("/**\n * Glyph bitmaps of the pixel fonts, generated from their TTF/WOFF files at native pixel size, without anti-aliasing.\n"
           " * Each glyph: code,advance,xOffset,top,width,height,hex rows. Fonts (SIL Open Font License 1.1):\n"
           " * Tiny5 (Tiny5 Project Authors), Departure Mono (Helena Zhang), Press Start 2P (CodeMan38), Silkscreen (Jason Kottke).\n"
           " * Generated by tools/fontgen.py: do not edit by hand. Licences in licenses/.\n */\nfinal class FontData {\n    private FontData() {}\n")
for name, path, size, lh in FONTS:
    font = ImageFont.truetype(os.path.join(HERE, path), size)
    entries = []
    caps = font.getmask2("H", mode="1", anchor="ls")
    cap = -caps[1][1]
    for c in CHARS:
        ch = chr(c)
        adv = font.getlength(ch)
        if abs(adv - round(adv)) > 0.01: print(name, "non-integer advance", ch, adv, file=sys.stderr)
        adv = int(round(adv))
        if adv == 0 and ch.strip(): continue
        im = Image.new("1", (size * 4, size * 4), 0)
        d = ImageDraw.Draw(im); d.fontmode = "1"
        ox, oy = size, size * 3  # baseline origin
        d.text((ox, oy), ch, font=font, fill=1, anchor="ls")
        bb = im.getbbox()
        if bb is None:
            entries.append(f"{c},{adv},0,0,0,0,")
            continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        rows = []
        for y in range(y0, y1):
            bits = 0
            for x in range(x0, x1):
                bits = (bits << 1) | (1 if im.getpixel((x, y)) else 0)
            rows.append(format(bits, "x"))
        entries.append(f"{c},{adv},{x0 - ox},{oy - y0},{w},{h}," + ".".join(rows))
    data = ";".join(entries)
    out.append(f"    /** cap height {cap}, line height {lh}. */")
    out.append(f"    static final int {name}_CAP = {cap}, {name}_LINE = {lh};")
    chunks = [data[i:i + 100] for i in range(0, len(data), 100)]
    out.append(f"    static final String {name} = \"\"\n" + "\n".join(f"            + \"{ch}\"" for ch in chunks) + ";\n")
out.append("}\n")
open(sys.argv[1], "w").write("\n".join(out))
print("ok")
